/*
# Attendance Approval Workflow + Session Feedback

## Overview
This migration changes the attendance flow so that:
1. Youth members enter an OTP and submit feedback.
2. The attendance record is created with status 'pending'.
3. The Local Youth Secretary approves or rejects the pending attendance.
4. Only after approval is the attendance considered 'present'.
5. OTP generation is restricted to local_youth_secretary role.
6. Feedback submitted during attendance is only readable by super_admin.

## New Tables

### attendance_feedback
- `id` (uuid, PK)
- `attendance_id` (uuid, FK to attendance, CASCADE)
- `youth_member_id` (uuid, FK to youth_members, CASCADE)
- `feedback_text` (text)
- `rating` (int 1-5)
- `created_at` (timestamptz)
- This is the feedback a youth member submits right after entering the OTP.

## Modified Tables

### attendance
- Added `status` (text, default 'pending') — 'pending', 'approved', 'rejected'
- Added `feedback_submitted` (boolean, default false)
- Added `approved_by` (uuid, FK to auth.users, nullable)
- Added `approved_at` (timestamptz, nullable)

## Security Changes

### attendance policies
- INSERT: youth_member, local_youth_secretary, secretary, treasurer can insert
  (youth members create pending records; leaders can also mark directly)
- UPDATE: local_youth_secretary can update status (approve/reject) for their church.
  Also super_admin can update any.
- SELECT: church members can read their church's attendance (but feedback is separate)

### attendance_feedback policies
- SELECT: only super_admin can read feedback
- INSERT: youth_member can insert their own feedback
- This ensures feedback is private to the super admin only.

### otp_sessions policies
- INSERT for 'attendance' type: restricted to local_youth_secretary only
  (secretary and treasurer can no longer generate attendance OTPs)
- secretary_enable OTPs can still be generated by church_admin

## Notes
1. Existing attendance records get status='approved' and feedback_submitted=true
   so they remain visible as before.
2. The local_youth_secretary is the sole approver of pending attendance.
3. PC members and other leaders can view attendance records but NOT feedback.
*/

-- ===== Add columns to attendance =====

ALTER TABLE public.attendance
  ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'pending',
  ADD COLUMN IF NOT EXISTS feedback_submitted boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS approved_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS approved_at timestamptz;

-- Backfill existing records as approved
UPDATE public.attendance SET status = 'approved', feedback_submitted = true WHERE status = 'pending' AND created_at < now() - interval '1 day';

CREATE INDEX IF NOT EXISTS idx_attendance_status ON public.attendance(status);

-- ===== attendance_feedback table =====

CREATE TABLE IF NOT EXISTS public.attendance_feedback (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  attendance_id uuid NOT NULL REFERENCES public.attendance(id) ON DELETE CASCADE,
  youth_member_id uuid NOT NULL REFERENCES public.youth_members(id) ON DELETE CASCADE,
  feedback_text text NOT NULL DEFAULT '',
  rating int NOT NULL DEFAULT 3 CHECK (rating >= 1 AND rating <= 5),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_att_feedback_member ON public.attendance_feedback(youth_member_id);
CREATE INDEX IF NOT EXISTS idx_att_feedback_attendance ON public.attendance_feedback(attendance_id);

ALTER TABLE public.attendance_feedback ENABLE ROW LEVEL SECURITY;

-- Only super_admin can read attendance feedback
DROP POLICY IF EXISTS "read_attendance_feedback" ON public.attendance_feedback;
CREATE POLICY "read_attendance_feedback" ON public.attendance_feedback FOR SELECT
  TO authenticated USING (public.get_user_role() = 'super_admin');

-- Youth members can insert their own feedback
DROP POLICY IF EXISTS "insert_attendance_feedback" ON public.attendance_feedback;
CREATE POLICY "insert_attendance_feedback" ON public.attendance_feedback FOR INSERT
  TO authenticated WITH CHECK (
    public.get_user_role() = 'youth_member'
  );

-- ===== Update attendance policies =====

-- Drop old insert policy and create new one with expanded roles
DROP POLICY IF EXISTS "insert_attendance" ON public.attendance;
CREATE POLICY "insert_attendance" ON public.attendance FOR INSERT
  TO authenticated WITH CHECK (
    church_id = public.get_user_church_id()
    AND public.get_user_role() IN ('secretary', 'treasurer', 'youth_member', 'local_youth_secretary', 'local_youth_treasurer')
  );

-- Update policy: local_youth_secretary can approve/reject, super_admin can update any
DROP POLICY IF EXISTS "update_attendance" ON public.attendance;
CREATE POLICY "update_attendance" ON public.attendance FOR UPDATE
  TO authenticated USING (
    church_id = public.get_user_church_id()
    OR public.get_user_role() = 'super_admin'
  )
  WITH CHECK (
    church_id = public.get_user_church_id()
    OR public.get_user_role() = 'super_admin'
  );

-- Keep existing read and delete policies
-- read_attendance and delete_attendance already exist

-- ===== Restrict attendance OTP generation to local_youth_secretary =====
-- We need a policy that restricts OTP session INSERT for 'attendance' type
-- to local_youth_secretary only. secretary_enable type stays with church_admin.

-- First, let's check existing OTP policies
-- We need to drop and recreate with the new restriction

-- Drop existing insert policy for otp_sessions if it exists
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_policy WHERE polname = 'insert_otp_sessions' AND polrelid = 'public.otp_sessions'::regclass) THEN
    DROP POLICY "insert_otp_sessions" ON public.otp_sessions;
  END IF;
END $$;

-- Create new insert policy: church_admin for secretary_enable, local_youth_secretary for attendance
CREATE POLICY "insert_otp_sessions" ON public.otp_sessions FOR INSERT
  TO authenticated WITH CHECK (
    church_id = public.get_user_church_id()
    AND (
      (type = 'secretary_enable' AND public.get_user_role() IN ('church_admin', 'super_admin'))
      OR
      (type = 'attendance' AND public.get_user_role() = 'local_youth_secretary')
    )
  );
